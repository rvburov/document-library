#!/bin/bash
#
# Тело релиза для GitHub. Печатает готовый markdown в stdout.
#
#   Scripts/github-release/release-notes.sh 1.0.4              # посмотреть, что получится
#   Scripts/github-release/release-notes.sh 1.0.4 > notes.md   # так вызывает workflow
#
# Состав: описание версии из release-history.md → какой файл качать → что нажать при первом
# запуске → как обновить сетевую папку → лицензия. Ничего лишнего: страница релиза — это
# место, где человек скачивает программу, а не читает отчет о работе.
#
# Сети и gh не требует: собирается целиком из файлов репозитория.
set -uo pipefail

ROOT="$(cd "$(dirname "$0")/../.." && pwd)"
HISTORY="$ROOT/Scripts/github-release/release-history.md"
VERSION="${1:-}"

[ -n "$VERSION" ] || { echo "Использование: release-notes.sh <версия>" >&2; exit 1; }
[ -f "$HISTORY" ] || { echo "Нет файла release-history.md" >&2; exit 1; }

# ── Что нового: секция «## [версия]» до следующего «## [» ─────────────────────
BODY="$(awk -v v="${VERSION//./\\.}" '
  $0 ~ "^## \\[" v "\\]" { found = 1; next }
  found && /^## \[/      { exit }
  # Сноски-ссылки в конце файла («[1.0.3]: https://…») — часть разметки истории, а не
  # описания версии. Секция самой свежей версии идет последней, и без этой строки они
  # каждый раз утекали бы в тело релиза.
  found && /^\[[^]]*\]:/ { next }
  found                  { print }
' "$HISTORY")"

# Обрезать пустые строки в начале секции; в конце их уже съела подстановка $(...).
BODY="$(printf '%s\n' "$BODY" | sed -e '/./,$!d')"

if [ -z "$BODY" ]; then
  echo "В release-history.md нет непустой секции «## [$VERSION]»" >&2
  exit 1
fi

echo "## Что нового"
echo
printf '%s\n' "$BODY"
echo
cat <<EOF
## Установка

| ОС | Файл | Что делать |
|---|---|---|
| Windows | \`PdfLibrary-Setup.exe\` | скачать и запустить |
| macOS, Apple Silicon | \`PdfLibrary-$VERSION-osx-arm64.dmg\` | открыть образ, запустить значок в окне |
| macOS, Intel | \`PdfLibrary-$VERSION-osx-x64.dmg\` | то же |
| Linux | \`PdfLibrary-$VERSION-linux-x64.tar.gz\` | \`tar -xzf …\`, затем \`./PdfLibrary-Setup\` |

Скачивается **один файл** — установщик \`PdfLibrary-Setup\`. Он ставит программу
(Windows — в \`%LOCALAPPDATA%\\Programs\`, macOS — в \`~/Applications\`, Linux — в \`~/.local/opt\`),
создает ярлыки и умеет удалять себя ключом \`--uninstall\`. .NET ставить не нужно:
среда выполнения внутри.

### Первый запуск

Система спросит подтверждение — один раз, только для установщика. Установленная
программа запускается дальше обычным двойным кликом.

**Windows.** Появится синее окно «Система Windows защитила ваш компьютер»:

1. Нажмите **«Подробнее»**.
2. Внизу окна появится кнопка **«Выполнить в любом случае»** — нажмите ее.

**macOS.** Инструкция нарисована прямо в окне образа, коротко:

1. Двойной клик по значку в окне образа.
2. Появится окно про проверку программы — нажмите **«Готово»**.
3. Откройте **Системные настройки ▸ Конфиденциальность и безопасность** и прокрутите
   вниз до раздела **«Безопасность»**.
4. Рядом с названием программы нажмите **«Все равно открыть»** и подтвердите.

**Linux.** Ничего дополнительно делать не нужно.

> Не переименовывайте установщик. Режим установки включается по окончанию имени
> \`-Setup\`; файл \`PdfLibrary-Setup (1).exe\`, который создает браузер при повторном
> скачивании, запустится как обычная программа, а не как установщик.

## Автообновление

Автообновление внутри программы берет файлы из папки обновлений (Настройки → О программе), а не
с GitHub.
Чтобы обновить пользователей, распакуйте архив в эту папку так, чтобы \`PdfLibrary-Setup*\`
оказался **в ее корне**. Подробности — \`docs/developer/guides/install-and-update.md\`.
EOF

# Списка коммитов в теле нет намеренно: что изменилось — сказано человеческим языком
# в разделе выше, а полная история и так на расстоянии одной ссылки со страницы релиза.
