using System.Globalization;

namespace PdfLibrary.Views.Library;

/// <summary>
/// Строка «показано не все» над страницами панели чтения. Чистая логика без Avalonia, поэтому
/// проверяется тестами.
///
/// У панели есть потолки, и они нужны: том на девятьсот страниц не должен съесть память ради
/// одного открытия. Плохо было бы другое — оборвать документ МОЛЧА: человек читал бы обрезанный
/// документ как целый.
/// </summary>
public static class DocCutNote
{
    // Куда идти за остальным: целиком документ показывает программа, в которой он открывается.
    private const string OpenHint = "Целиком документ открывается кнопкой «Открыть» на его карточке.";

    /// <summary>Страницы тома за потолком панели; пусто — показан весь.</summary>
    public static string ForPages(int shown, int total) =>
        shown > 0 && shown < total ? $"Показаны страницы 1–{N(shown)} из {N(total)}. {OpenHint}" : "";

    /// <summary>
    /// Число с разделителем разрядов — неразрывным пробелом: «5 400», а не «5400», и строка не
    /// переносится посреди числа. Не через культуру системы: у нее разделитель свой, а строка
    /// обязана выглядеть одинаково везде.
    /// </summary>
    public static string N(int n) =>
        n.ToString("#,0", CultureInfo.InvariantCulture).Replace(",", " ");
}
